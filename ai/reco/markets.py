def area_of(mxtr_nm: str):
    """조합 이름 → 권역 이름 (없으면 None: 서해·내륙 소비지 시장 등은 이 프로젝트에서 뺀다)."""
    for name, *_, words in AREAS:
        if any(w in mxtr_nm for w in words):
            return name
    return None


def areas_table() -> pd.DataFrame:
    return pd.DataFrame([a[:5] for a in AREAS], columns=["area", "station_code", "station", "lat", "lon"])


def markets_table(daily: pd.DataFrame) -> pd.DataFrame:
    """위판 하루 집계 → 위판장 목록 + 권역 + 관측소 + 중량 합(톤)."""
    m = (daily.groupby(["mxtrNm", "csmtmktNm"], as_index=False)["weight_kg"].sum())
    m["area"] = m["mxtrNm"].map(area_of)
    m = m.merge(areas_table(), on="area", how="left")
    m["weight_t"] = (m.pop("weight_kg") / 1000).round(1)
    return m.sort_values("weight_t", ascending=False)
